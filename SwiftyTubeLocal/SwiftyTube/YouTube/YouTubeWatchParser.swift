import Foundation

/// Parsers for the `/next` watch response (related rows, chapters, transcript
/// params) and for `get_transcript`.
public enum YouTubeWatchParser: Sendable {
    /// Watch-page data for `videoId` from a `/next` response.
    public static func watch(in json: [String: Any], videoId: String) -> YouTubeWatch {
        let related = relatedVideos(in: json, excluding: videoId)
        return YouTubeWatch(
            video: currentVideo(in: json, videoId: videoId),
            related: related,
            chapters: chapters(in: json),
            transcriptParams: transcriptParams(in: json),
            commentsContinuation: commentsContinuation(in: json),
            continuation: YouTubeFeedParser.continuation(in: json)
        )
    }

    /// Transcript segments from a `get_transcript` response. Handles both the
    /// `transcriptSegmentRenderer` and `transcriptCueRenderer` shapes.
    public static func transcript(in json: [String: Any]) -> [YouTubeTranscriptSegment] {
        var out: [YouTubeTranscriptSegment] = []
        YouTubeFeedParser.walk(json) { renderer, key in
            switch key {
            case "transcriptSegmentRenderer":
                let text = InnerTubeDecode.runsTextTolerant(renderer["snippet"]) ?? ""
                guard !text.isEmpty else { return }
                out.append(YouTubeTranscriptSegment(
                    text: text,
                    startMilliseconds: InnerTubeDecode.intFromStringOrInt(renderer["startMs"]) ?? 0,
                    durationMilliseconds: durationMs(from: renderer)
                ))
            case "transcriptCueRenderer":
                let text = InnerTubeDecode.runsTextTolerant(renderer["cue"]) ?? ""
                guard !text.isEmpty else { return }
                out.append(YouTubeTranscriptSegment(
                    text: text,
                    startMilliseconds: InnerTubeDecode.intFromStringOrInt(renderer["startOffsetMs"]) ?? 0,
                    durationMilliseconds: InnerTubeDecode.intFromStringOrInt(renderer["durationMs"])
                ))
            default:
                break
            }
        }
        return out
    }

    /// Caption tracks from a `/player` response. Fetch `baseURL + "&fmt=json3"`
    /// to get segments without a PoToken.
    public static func captionTracks(in json: [String: Any]) -> [YouTubeCaptionTrack] {
        guard let tracks = InnerTubeDecode.array(
            at: ["captions", "playerCaptionsTracklistRenderer", "captionTracks"], in: json
        ) else { return [] }
        return tracks.map { track in
            YouTubeCaptionTrack(
                languageCode: track["languageCode"] as? String,
                name: InnerTubeDecode.string(at: ["name", "simpleText"], in: track)
                    ?? InnerTubeDecode.runsTextTolerant(track["name"]),
                isAutoGenerated: (track["kind"] as? String) == "asr",
                baseURL: track["baseUrl"] as? String
            )
        }
    }

    /// Typed variant from a decoded player response.
    public static func captionTracks(from response: PlayerResponse) -> [YouTubeCaptionTrack] {
        (response.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? []).map { track in
            YouTubeCaptionTrack(
                languageCode: track.languageCode,
                name: track.name?.text,
                isAutoGenerated: track.isAutoGenerated,
                baseURL: track.baseUrl
            )
        }
    }

    // MARK: - Watch internals

    private static func durationMs(from renderer: [String: Any]) -> Int? {
        guard let end = InnerTubeDecode.intFromStringOrInt(renderer["endMs"]),
              let start = InnerTubeDecode.intFromStringOrInt(renderer["startMs"]) else { return nil }
        return max(end - start, 0)
    }

    static func currentVideo(in json: [String: Any], videoId: String) -> YouTubeVideo? {
        var title: String?
        var viewCount: String?
        var owner: [String: Any]?

        YouTubeFeedParser.walk(json) { renderer, key in
            switch key {
            case "videoPrimaryInfoRenderer":
                title = title ?? InnerTubeDecode.runsTextTolerant(renderer["title"])
                viewCount = viewCount ?? viewCountText(renderer)
            case "videoSecondaryInfoRenderer":
                owner = owner ?? InnerTubeDecode.dict(at: ["owner", "videoOwnerRenderer"], in: renderer)
            default:
                break
            }
        }

        guard title != nil || owner != nil else { return nil }
        let channelId = owner.flatMap { YouTubeFeedParser.channelIdFromNavigation($0) }
        return YouTubeVideo(
            videoId: videoId,
            title: title ?? "",
            channelTitle: owner.flatMap { InnerTubeDecode.runsTextTolerant($0["title"]) },
            channelId: channelId,
            durationSeconds: nil,
            thumbnailURL: nil,
            viewCountText: viewCount,
            publishedTimeText: nil,
            isLive: false,
            isShort: false
        )
    }

    private static func viewCountText(_ renderer: [String: Any]) -> String? {
        InnerTubeDecode.string(
            at: ["viewCount", "videoViewCountRenderer", "viewCount", "simpleText"], in: renderer
        ) ?? InnerTubeDecode.string(
            at: ["viewCount", "videoViewCountRenderer", "shortViewCount", "simpleText"], in: renderer
        )
    }

    static func relatedVideos(in json: [String: Any], excluding videoId: String) -> [YouTubeVideo] {
        let subtree = InnerTubeDecode.dict(
            at: ["contents", "twoColumnWatchNextResults", "secondaryResults", "secondaryResults"], in: json
        )
        let source = subtree ?? json
        return YouTubeFeedParser.videos(in: source).filter { $0.videoId != videoId }
    }

    static func chapters(in json: [String: Any]) -> [YouTubeChapter] {
        var out: [YouTubeChapter] = []
        YouTubeFeedParser.walk(json) { renderer, key in
            guard key == "chapterRenderer" else { return }
            let title = InnerTubeDecode.runsTextTolerant(renderer["title"])
                ?? InnerTubeDecode.string(at: ["title", "simpleText"], in: renderer)
                ?? ""
            guard !title.isEmpty else { return }
            let startMs = InnerTubeDecode.intFromStringOrInt(renderer["timeRangeStartMillis"]) ?? 0
            out.append(YouTubeChapter(
                title: title,
                startSeconds: startMs / 1000,
                thumbnailURL: InnerTubeDecode.thumbnailURLTolerant(renderer)
            ))
        }
        return out
    }

    static func transcriptParams(in json: [String: Any]) -> String? {
        var params: String?
        YouTubeFeedParser.walk(json) { renderer, key in
            guard params == nil, key == "getTranscriptEndpoint" else { return }
            params = renderer["params"] as? String
        }
        return params
    }

    static func commentsContinuation(in json: [String: Any]) -> String? {
        var token: String?
        YouTubeFeedParser.walk(json) { renderer, key in
            guard token == nil, key == "itemSectionRenderer",
                  renderer["sectionIdentifier"] as? String == "comment-item-section" else { return }
            token = YouTubeFeedParser.continuation(in: renderer)
        }
        return token
    }
}
